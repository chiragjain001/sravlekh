@pytest.mark.asyncio
async def test_concurrent_duplicate_evaluation_events_produce_exactly_one_assignment():
    """Simulates two mastery-recalc jobs for the same student+topic racing
    each other (e.g. a BullMQ retry alongside the original attempt) against a
    single shared, stateful fake MasteryScore row — proving the atomicity is
    in the update_many WHERE clause itself, not in call ordering. Same
    Promise.allSettled-against-a-stateful-mock technique used for the
    NestJS-side concurrency tests in this codebase (assessments.service.spec.ts).
    """
    claim_state = {"claimed": False}

    async def racy_update_many(where, data):
        # Simulates Postgres row-level locking: only the first caller whose
        # WHERE still matches (interventionTriggeredAt IS NULL) succeeds.
        await asyncio.sleep(0)  # yield control, so both tasks interleave here
        if claim_state["claimed"]:
            return 0
        claim_state["claimed"] = True
        return 1

    fake_db = make_fake_db()
    fake_db.masteryscore.update_many = racy_update_many

    with patch("src.analytics.intervention_engine.db", fake_db):
        await asyncio.gather(
            evaluate_interventions("student-1", [("topic-1", "sub-1", 0.2)]),
            evaluate_interventions("student-1", [("topic-1", "sub-1", 0.2)]),
        )

    assert fake_db.assignment.create.await_count == 1
    assert fake_db.intervention.create.await_count == 1
    assert fake_db.notice.create.await_count == 1

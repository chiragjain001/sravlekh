def make_student(batch_id="batch-1", institute_id="inst-1"):
    return SimpleNamespace(batchId=batch_id, user=SimpleNamespace(instituteId=institute_id))


def make_batch_teacher(teacher_user_id="teacher-1"):
    return SimpleNamespace(teacherProfile=SimpleNamespace(user=SimpleNamespace(id=teacher_user_id)))


def make_fake_db(
    student=None,
    batch_teacher="default",
    update_many_result=1,
    questions=None,
    topic_name="Rotational Motion",
):
    return SimpleNamespace(
        studentprofile=SimpleNamespace(find_unique=AsyncMock(return_value=student if student is not None else make_student())),
        batchteacher=SimpleNamespace(
            find_first=AsyncMock(return_value=make_batch_teacher() if batch_teacher == "default" else batch_teacher)
        ),
        masteryscore=SimpleNamespace(update_many=AsyncMock(return_value=update_many_result)),
        topic=SimpleNamespace(find_unique=AsyncMock(return_value=SimpleNamespace(name=topic_name))),
        question=SimpleNamespace(find_many=AsyncMock(return_value=questions if questions is not None else [])),
        assignment=SimpleNamespace(create=AsyncMock(return_value=SimpleNamespace(id="assign-1"))),
        intervention=SimpleNamespace(create=AsyncMock(return_value=SimpleNamespace(id="interv-1"))),
        notice=SimpleNamespace(create=AsyncMock(return_value=SimpleNamespace(id="notice-1"))),
        noticedelivery=SimpleNamespace(create=AsyncMock()),
        timetableslot=SimpleNamespace(create=AsyncMock()),  # present only so a stray call would be caught, never expected to be used
    )


@pytest.mark.asyncio
async def test_no_weak_topics_does_nothing():
    fake_db = make_fake_db()
    with patch("src.analytics.intervention_engine.db", fake_db):
        await evaluate_interventions("student-1", [("topic-1", "sub-1", 0.9)])

    fake_db.studentprofile.find_unique.assert_not_awaited()
    fake_db.assignment.create.assert_not_awaited()


@pytest.mark.asyncio
async def test_weak_topic_below_threshold_creates_one_assignment_one_intervention_one_notification():
    fake_db = make_fake_db()
    with patch("src.analytics.intervention_engine.db", fake_db):
        await evaluate_interventions("student-1", [("topic-1", "sub-1", 0.3)])

    fake_db.assignment.create.assert_awaited_once()
    fake_db.intervention.create.assert_awaited_once()
    fake_db.notice.create.assert_awaited_once()
    fake_db.noticedelivery.create.assert_awaited_once()

    assignment_data = fake_db.assignment.create.await_args.kwargs["data"]
    assert assignment_data["studentProfileId"] == "student-1"
    assert assignment_data["topicId"] == "topic-1"
    assert assignment_data["isAutoGenerated"] is True

    intervention_data = fake_db.intervention.create.await_args.kwargs["data"]
    assert intervention_data["type"] == "ASSIGNMENT"
    assert intervention_data["topicId"] == "topic-1"
    assert intervention_data["beforeMastery"] == 0.3



logger = logging.getLogger(__name__)

router = APIRouter(prefix="/analytics", tags=["Analytics & Insights"])


class RecalculateMasteryRequest(BaseModel):
    studentProfileId: str
    topicIds: list[str]


class DiagnosticRemediationRequest(BaseModel):
    instituteId: str
    studentProfileId: str
    topicId: str
    masteryScore: float


class GrowthScoreRequest(BaseModel):
    students: list[dict[str, Any]]
    filterSubjectId: Optional[str] = None
    filterExamFamily: Optional[str] = None
    filterPeriodWeeks: Optional[int] = None
    targetStudentId: Optional[str] = None


@router.post("/recalculate-mastery", dependencies=[Depends(verify_internal_token)])
async def recalculate_mastery_endpoint(request: RecalculateMasteryRequest):
    """Internal-only (D-02): called by apps/api's mastery-recalc BullMQ processor
    after a grading commit. Durability/retry lives in that queue, not here — this
    endpoint just does the calculation and returns once it's done."""
    await recalculate_mastery(request.studentProfileId, request.topicIds)
    return {"success": True}


@router.post("/diagnostic-remediation", dependencies=[Depends(verify_internal_token)])
async def diagnostic_remediation_endpoint(request: DiagnosticRemediationRequest):
    """05-API-SPECIFICATION.md §16: Diagnostic remediation trigger for a student topic gap."""
    await ensure_db()
    topic = await db.topic.find_unique(where={"id": request.topicId}, include={"chapter": True})
    subject_id = topic.chapter.subjectId if topic and topic.chapter else "UNKNOWN"
    await evaluate_interventions(
        request.studentProfileId,
        [(request.topicId, subject_id, request.masteryScore)],
    )
    latest_intervention = await db.intervention.find_first(
        where={"studentProfileId": request.studentProfileId, "topicId": request.topicId},
        order={"createdAt": "desc"},
    )
    latest_assignment = await db.assignment.find_first(
        where={"studentProfileId": request.studentProfileId, "topicId": request.topicId, "isAutoGenerated": True},
        order={"createdAt": "desc"},
    )
    return {
        "success": True,
        "interventionId": latest_intervention.id if latest_intervention else None,
        "assignmentId": latest_assignment.id if latest_assignment else None,
    }


@router.post("/growth-score", dependencies=[Depends(verify_internal_token)])
async def compute_growth_score_endpoint(request: GrowthScoreRequest):
    """Growth & Momentum engine endpoint called by apps/api Leaderboard module."""
    result = calculate_cohort_growth(
        students=request.students,
        filter_subject_id=request.filterSubjectId,
        filter_exam_family=request.filterExamFamily,
        filter_period_weeks=request.filterPeriodWeeks,
        target_student_id=request.targetStudentId,
    )
    return result

@router.get("/batches/heatmap")
async def get_batches_heatmap(
    batchIds: str,
    current_user = Depends(get_current_user),
):
    """
    Heatmaps for several batches at once, keyed by batch id.

    C-4 fix: replaced Prisma findMany + Pandas groupby with a single PostgreSQL
    GROUP BY query. The old approach loaded every StudentProfile.masteryScores row
    into Python (O(students x topics) rows), flattened them to a list, and handed
    it to Pandas for a simple average + count. PostgreSQL GROUP BY returns only
    O(batches x topics) summary rows in one round-trip.
    """
    if current_user.role not in ["TEACHER", "ADMIN", "FOUNDER"]:
        raise HTTPException(status_code=403, detail="Forbidden")

    ids = [b for b in (batchIds or "").split(",") if b]
    if not ids:
        return {"success": True, "data": {}}
    if len(ids) > 50:
        raise HTTPException(status_code=400, detail="At most 50 batches per request.")

    try:
        await ensure_db()
        heatmap_by_batch = await _query_heatmap_by_batch(ids)
        return {"success": True, "data": heatmap_by_batch}
    except Exception as e:
        logger.exception(f"Error fetching heatmaps for batches {batchIds}: {e}")
        return {"success": True, "data": {b: [] for b in ids}}


@router.get("/batch/{batch_id}/heatmap")
async def get_batch_heatmap(batch_id: str, current_user = Depends(get_current_user)):
    """
    Topic-level struggle summary for a single batch.
    Uses the same SQL GROUP BY aggregation as the multi-batch endpoint.
    """
    if current_user.role not in ["TEACHER", "ADMIN", "FOUNDER"]:
        raise HTTPException(status_code=403, detail="Forbidden")

    try:
        await ensure_db()
        result = await _query_heatmap_by_batch([batch_id])
        return {"success": True, "data": result.get(batch_id, [])}
    except Exception as e:
        logger.exception(f"Error fetching heatmap for batch {batch_id}: {e}")
        return {"success": True, "data": []}


async def _query_heatmap_by_batch(batch_ids: list[str]) -> dict[str, list]:
    """
    Single PostgreSQL GROUP BY query returning per-batch, per-topic mastery aggregates.

    WHY SQL instead of Pandas (C-4 fix):
    The previous approach loaded StudentProfile + masteryScores into Python then
    ran Pandas groupby to compute per-topic averages. For a school with 500 students
    and 50 topics that is 25,000 rows fetched and deserialized before any aggregation.
    PostgreSQL GROUP BY returns len(unique topics across batches) rows directly.

    mastery_value in mastery_scores is 0-1 scale; multiply by 100 in SQL for the
    percentage the UI expects, matching the previous *100.0 transformation.
    """
    mastery_threshold = get_mastery_threshold()
    critical_pct = get_heatmap_critical_threshold_pct()
    warning_pct = get_heatmap_warning_threshold_pct()
    # mastery_threshold is 0-1; the SQL compares against the raw column (also 0-1)
    threshold_raw = mastery_threshold

    rows = await db.query_raw(
        """
        SELECT
          sp."batchId"                                          AS batch_id,
          ms."topicId"                                         AS topic_id,
          t."name"                                             AS topic_name,
          ROUND((AVG(ms."masteryValue") * 100)::numeric, 1)   AS avg_mastery,
          COUNT(CASE WHEN ms."masteryValue" < $1 THEN 1 END)  AS struggling,
          COUNT(*)                                             AS total
        FROM mastery_scores ms
        JOIN student_profiles sp ON sp.id = ms."studentProfileId"
        LEFT JOIN topics t ON t.id = ms."topicId"
        WHERE sp."batchId" = ANY($2)
        GROUP BY sp."batchId", ms."topicId", t."name"
        ORDER BY avg_mastery ASC
        """,
        threshold_raw,
        batch_ids,
    )

    result: dict[str, list] = {b: [] for b in batch_ids}
    for row in rows:
        bid = row["batch_id"]
        avg_m = float(row["avg_mastery"] or 0.0)
        total = int(row["total"] or 0)
        struggling = int(row["struggling"] or 0)
        struggle_pct = round((struggling / total * 100) if total > 0 else 0.0, 1)
        status = "CRITICAL" if avg_m < critical_pct else "WARNING" if avg_m < warning_pct else "HEALTHY"

        result.setdefault(bid, []).append({
            "topicId": row["topic_id"],
            "topicName": row["topic_name"] or f"Topic {row['topic_id']}",
            "averageMastery": avg_m,
            "studentsStruggling": struggling,
            "totalStudents": total,
            "strugglePercentage": struggle_pct,
            "status": status,
        })

    return result


@router.get("/evaluation-quality")
async def get_evaluation_quality(
    instituteId: str | None = None,
    modelVersion: str | None = None,
    dateFrom: str | None = None,
    dateTo: str | None = None,
    segmentBy: str | None = None,
    current_user=Depends(get_current_user),
):
    """05-API-SPECIFICATION.md (V2 section) §9 / 31 §3, backing
    AdminEvaluationQualityDashboard. instituteId is only honored for FOUNDER
    (cross-tenant) — an ADMIN always sees their own institute regardless of
    what they pass. segmentBy (32-AI-GOVERNANCE-POLICY.md §4's opt-in,
    privacy-sensitive per-subgroup breakdown) is accepted but not implemented
    — real consent-gating infrastructure per institute would be needed first,
    flagged rather than faked with an unguarded breakdown."""
    if current_user.role not in ["ADMIN", "FOUNDER"]:
        raise HTTPException(status_code=403, detail="Forbidden")

    institute_id = instituteId if (current_user.role == "FOUNDER" and instituteId) else current_user.instituteId

    data = await compute_evaluation_quality(institute_id, modelVersion, dateFrom, dateTo)
    if segmentBy:
        data["segmentation"] = {"requested": segmentBy, "note": "not yet implemented — requires per-institute opt-in consent infrastructure (32 §4)"}

    return {"success": True, "data": data}

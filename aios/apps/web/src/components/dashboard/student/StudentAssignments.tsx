interface Assignment {
  id: string;
  title: string;
  description?: string | null;
  dueDate: string;
  status: 'PENDING' | 'SUBMITTED' | 'LATE_SUBMITTED' | 'GRADED' | 'MISSED';
  topic?: {
    name: string;
    chapter?: {
      subject?: {
        name: string;
      };
    };
  };
  gradedMarks?: number | null;
  isAutoGenerated: boolean;
}

type Tab = 'pending' | 'submitted' | 'completed';
const TAB_STATUSES: Record<Tab, Assignment['status'][]> = {
  pending: ['PENDING'],
  submitted: ['SUBMITTED', 'LATE_SUBMITTED'],
  completed: ['GRADED'],
};

function formatFileSize(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

function extractAssignmentSubject(a: Assignment): string {
  if (a.topic?.chapter?.subject?.name && isStudentClassSubject(a.topic.chapter.subject.name)) {
    return a.topic.chapter.subject.name;
  }
  const text = `${a.title} ${a.topic?.name ?? ''} ${a.description ?? ''}`.toLowerCase();
  if (
    text.includes('physic') ||
    text.includes('motion') ||
    text.includes('kinematics') ||
    text.includes('torque') ||
    text.includes('vector') ||
    text.includes('rotation') ||
    text.includes('optics') ||
    text.includes('thermodynamic') ||
    text.includes('gravity') ||
    text.includes('friction')
  ) {
    return 'Physics';
  }
  if (
    text.includes('chem') ||
    text.includes('organic') ||
    text.includes('mole') ||
    text.includes('equilibrium') ||
    text.includes('bonding') ||
    text.includes('atomic') ||
    text.includes('acid') ||
    text.includes('reaction')
  ) {
    return 'Chemistry';
  }
  if (
    text.includes('math') ||
    text.includes('calculus') ||
    text.includes('trig') ||
    text.includes('integral') ||
    text.includes('conic') ||
    text.includes('algebra') ||
    text.includes('set') ||
    text.includes('derivative')
  ) {
    return 'Mathematics';
  }
  return 'Physics';
}

function getSubjectBadge(subject: string) {
  switch (subject) {
    case 'Physics':
      return 'bg-blue-50 text-blue-700 border-blue-200/80';
    case 'Chemistry':
      return 'bg-emerald-50 text-emerald-700 border-emerald-200/80';
    case 'Mathematics':
      return 'bg-indigo-50 text-indigo-700 border-indigo-200/80';
    default:
      return 'bg-slate-100 text-slate-700 border-slate-200';
  }
}


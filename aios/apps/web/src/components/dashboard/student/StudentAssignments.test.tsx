import React from 'react';
import { render, screen, fireEvent } from '@testing-library/react';
import { describe, it, expect, vi } from 'vitest';
import { StudentAssignments } from './StudentAssignments';

vi.mock('@/hooks/useApi', () => ({
  useAssignments: () => ({
    data: {
      data: [
        {
          id: 'asg-1',
          title: 'Rotational Dynamics Problem Set',
          description: 'Solve problems 1-10 on moment of inertia',
          dueDate: new Date(Date.now() + 86400000 * 3).toISOString(),
          status: 'PENDING',
          isAutoGenerated: true,
          topic: {
            name: 'Rotational Motion',
            chapter: {
              subject: {
                name: 'Physics',
              },
            },
          },
        },
        {
          id: 'asg-2',
          title: 'Calculus Integration Exercises',
          description: 'Integration by parts worksheet',
          dueDate: new Date(Date.now() + 86400000 * 5).toISOString(),
          status: 'PENDING',
          isAutoGenerated: false,
          topic: {
            name: 'Integration',
            chapter: {
              subject: {
                name: 'Mathematics',
              },
            },
          },
        },
      ],
    },
    isPending: false,
  }),
  useSubmitAssignment: () => ({
    mutateAsync: vi.fn(),
    isPending: false,
  }),
}));

vi.mock('@/hooks/useAssignmentActions', () => ({
  useDeleteAssignmentSubmission: () => ({
    mutateAsync: vi.fn(),
    isPending: false,
  }),
  useAssignmentSubmissionUrl: () => ({
    data: null,
    isFetching: false,
  }),
}));

describe('StudentAssignments Screen', () => {
  it('renders assignment items and distinct Remedial Practice badge for auto-generated tasks', () => {
    render(<StudentAssignments />);

    expect(screen.getByText('Rotational Dynamics Problem Set')).toBeDefined();
    expect(screen.getByText('Calculus Integration Exercises')).toBeDefined();

    // Auto-generated remedial coursework badge is displayed
    const remedialBadges = screen.getAllByText('Remedial Practice');
    expect(remedialBadges.length).toBeGreaterThan(0);
  });

  it('opens submit modal when clicking submit on an assignment', () => {
    render(<StudentAssignments />);

    const submitButtons = screen.getAllByRole('button', { name: /submit work/i });
    expect(submitButtons.length).toBeGreaterThan(0);
    fireEvent.click(submitButtons[0]!);

    // Modal opens with title
    expect(screen.getByText('Submit Assignment')).toBeDefined();
    expect(screen.getByText(/Upload your completed coursework/i)).toBeDefined();
  });
});
